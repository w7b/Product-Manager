-- Pedidos (vendas) e seus itens.
CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id       BIGINT         NOT NULL REFERENCES stores (id),
    user_id        BIGINT         NOT NULL REFERENCES users (id),
    customer_name  VARCHAR(120),
    status         VARCHAR(20)    NOT NULL CHECK (status IN ('ABERTO', 'FINALIZADO', 'CANCELADO')),
    payment_method VARCHAR(20) CHECK (payment_method IN ('DINHEIRO', 'PIX', 'CARTAO_CREDITO', 'CARTAO_DEBITO')),
    total          NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at     TIMESTAMP(6)   NOT NULL,
    finished_at    TIMESTAMP(6)
);
CREATE INDEX ix_orders_store_status ON orders (store_id, status, finished_at);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id BIGINT         NOT NULL REFERENCES products (id),
    quantity   INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL,
    subtotal   NUMERIC(12, 2) NOT NULL
);
CREATE INDEX ix_order_items_order ON order_items (order_id);
